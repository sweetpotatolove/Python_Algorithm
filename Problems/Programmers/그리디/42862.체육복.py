# 프로그래머스 Lv1. 체육복
# 분류: 그리디
# 핵심: 학생 번호를 인덱스로 하는 배열에 보유 체육복 수(기본 1, 여벌이면 +1, 도난이면 -1)를 기록한 뒤, 체육복이 없는 학생은 바로 앞/뒤 학생 중 여벌(2벌)이 있는 학생에게 빌려 채운다.
# 시간 복잡도: O(n)
"""
    1. 입력 크기를 정의: 전체 학생 수 n, lost/reserve의 길이도 n 이하이므로 함께 n으로 취급한다.
    2. 코드에서 반복문·조건문의 실행 횟수를 입력 크기에 대한 함수로 센다.
    3. 상수 시간 연산(비교, 대입, 인덱스 접근)은 O(1)로 취급하고, 이런 연산이 반복문 안에서 몇 번 실행되는지 곱한다.
        -> for r_num in reserve, for l_num in lost는 각각 최대 n번,
        -> for i in range(1, n+1)이 두 번(빌려주기, 개수 세기) 등장해 각각 n번씩 실행되고,
        -> 각 반복 내부는 모두 O(1)이므로
        -> 전체 시간 = (n + n + n + n) × O(1) = O(n)
"""


# 공간 복잡도: O(n)
"""
    1. 입력 자체를 저장하는 공간은 보통 제외하고(입력은 이미 주어진 것이므로), 알고리즘이 추가로 사용하는 메모리만 센다.
    2. 입력 크기 n에 비례해서 커지는 자료구조(리스트, 딕셔너리 등)를 새로 만드는지 확인한다.
        -> 이 코드는 학생 수만큼 체육복 보유 개수를 저장하는 student 배열(문제 제한상 n+2 이하 크기)을 새로 만들므로
        -> 추가 공간 = 학생 수에 비례 = O(n)
"""


# 1. 문제 이해
# - 입력: 전체 학생 수 n, 도난당한 학생 번호 배열 lost, 여벌 체육복을 가져온 학생 번호 배열 reserve
# - 출력: 체육수업을 들을 수 있는 학생 수의 최댓값
# - 구해야 하는 것: 체육복이 없는 학생에게 바로 옆 번호 학생의 여벌 체육복을 최대한 빌려줬을 때, 체육복을 입을 수 있는 학생 수


# 2. 아이디어
# - 학생 번호를 인덱스로 하는 배열에 보유 체육복 수를 표시한다. 기본값 1(자기 체육복), reserve면 +1, lost면 -1.
# - reserve와 lost에 모두 포함된 학생은 +1, -1이 상쇄되어 1이 되므로, "도난당했지만 남에게는 못 빌려줌" 조건이 자연스럽게 처리된다.
# - 체육복이 0벌인 학생을 번호 순서대로 확인하며, 바로 앞 번호 학생이 2벌(여벌 보유)이면 빌리고, 아니면 바로 뒷번호 학생이 2벌이면 빌린다.
# - 앞 번호를 먼저 확인하는 이유: 순회가 번호 순서대로 진행되므로, 현재 i번 학생이 (i-1)번 학생에게 빌릴 수 있는 마지막 기회이기 때문이다. 뒷번호 학생은 이후 자기 차례가 오면 또 한 번 빌릴 기회가 있으므로 먼저 양보해도 된다.


# 3. 풀이 계획
# 1) reserve에 있는 학생의 student 값을 1 증가시킨다.
# 2) lost에 있는 학생의 student 값을 1 감소시킨다.
# 3) 1번부터 n번 학생까지 순회하며 student 값이 0이면, 앞 번호 학생이 2이면 그 학생에게서 1을 빌려오고, 그렇지 않고 뒷번호 학생이 2이면 그 학생에게서 1을 빌려온다.


def solution(n, lost, reserve):
    student = [1] * 32
    for r_num in reserve:
        # 여벌 가진 학생 체크
        student[r_num] += 1

    for l_num in lost:
        # 도난당한 학생 체크
        student[l_num] -= 1

    for i in range(1, n+1):
        if student[i] == 0:
            # 앞 번호 학생 체크
            if student[i-1] == 2:
                student[i-1] -= 1
                student[i] += 1
            # 뒷번호 학생 체크
            elif student[i+1] == 2:
                student[i+1] -= 1
                student[i] += 1
    
    answer = 0
    for i in range(1, n+1):
        if student[i] >= 1:
            answer += 1
    return answer