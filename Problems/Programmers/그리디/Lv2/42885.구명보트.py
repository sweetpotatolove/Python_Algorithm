# 시간 복잡도: O(n log n)
"""
    1. 입력 크기를 정의: people의 길이를 n(사람 수)이라 둔다.
    2. 코드에서 정렬·반복문의 실행 비용을 입력 크기에 대한 함수로 센다.
    3. people.sort()는 O(n log n)이 걸리고, while queue는 매 반복마다 가장 무거운 사람을 최소 1명 큐에서 빼내므로 최대 n번 반복되며,
        -> 반복 내부(pop, popleft, 비교)는 모두 O(1)이므로
        -> 전체 시간 = O(n log n) + n × O(1) = O(n log n)
"""


# 공간 복잡도: O(n)
"""
    1. 입력 자체를 저장하는 공간은 보통 제외하고(입력은 이미 주어진 것이므로), 알고리즘이 추가로 사용하는 메모리만 센다.
    2. 입력 크기 n에 비례해서 커지는 자료구조(리스트, 딕셔너리 등)를 새로 만드는지 확인한다.
        -> 이 코드는 people을 복사한 queue(deque, 크기 n)를 새로 만드므로
        -> 추가 공간 = 사람 수에 비례 = O(n)
"""


# 1. 문제 이해
# - 입력: 사람들의 몸무게 배열 people, 보트 한 척의 몸무게 제한 limit
# - 출력: 모든 사람을 구출하는 데 필요한 보트의 최소 개수
# - 구해야 하는 것: 보트 한 척에 최대 2명, 두 사람 몸무게 합이 limit 이하일 때만 함께 탈 수 있다는 조건에서 필요한 최소 보트 수


# 2. 아이디어
# - 몸무게로 정렬한 뒤, 가장 무거운 사람은 누구와 짝지어도 결국 처리해야 하므로 먼저 보트에 태운다(무거운 사람 우선 처리).
# - 이때 남은 사람 중 가장 가벼운 사람과 함께 탈 수 있는지 확인한다. 가장 가벼운 사람과도 함께 탈 수 없다면 다른 누구와도 함께 탈 수 없으므로, 가장 가벼운 사람이 짝지어질 최선의 후보다.
# - 함께 탈 수 있으면 둘을 같이 보내고, 아니면 무거운 사람 혼자 보낸다. 큐가 빌 때까지 반복하며 사용한 보트 수를 센다.


# 3. 풀이 계획
# 1) queue가 빌 때까지 반복하며 맨 뒤(가장 무거운 사람)를 꺼내 보트에 태운다.
# 2) queue에 사람이 남아있고, 맨 앞(가장 가벼운 사람)과 함께 타도 limit을 넘지 않으면, 그 사람도 함께 태우고 queue에서 제거한다.
# 3) 보트 한 척을 사용했으므로 answer를 1 증가시킨다.


from collections import deque
def solution(people, limit):
    people.sort()
    queue = deque(people)
    answer = 0

    while queue:
        # 젤 무거운 애 태우고
        h_p = queue.pop()

        # 만약 젤 가벼운 애랑 같이 태울 수 있으면 같이 태움
        if queue:
            if queue[0] + h_p <= limit:
                queue.popleft()

        answer += 1

    return answer