# 프로그래머스 Lv2. 올바른 괄호
# 분류: 스택/큐
# 핵심: '('는 스택에 쌓고 ')'를 만날 때마다 꺼내며, 스택이 비었는데 ')'가 오거나 끝까지 다 짝지어지지 않으면 올바르지 않은 괄호
# 시간 복잡도: O(n)
"""
    1. 코드에서 반복문을 찾는다 -> for idx in range(1, len(s))가 문자열 길이 n에 비례해 한 번씩 실행됨
    2. 루프 안의 각 연산 비용을 확인한다 -> stack.append(), stack.pop()은 모두 O(1)
    3. "루프 반복 횟수 * 반복 내부 연산 비용"을 곱한다 -> O(n) * O(1) = O(n)
"""
# 공간 복잡도: O(n)
"""
    1. 입력 크기에 비례해서 새로 만들어지는 자료구조를 찾는다 -> stack 리스트
    2. 최악의 경우 (ex. "((((((" 처럼 전부 '('인 경우) 스택에 최대 n개의 문자가 쌓일 수 있음 -> O(n)
"""


# 1. 문제 이해
# - 입력: 괄호 문자열 s (문자는 '(' 또는 ')'로만 구성)
# - 출력: 올바른 괄호 문자열이면 True, 아니면 False
# - 구해야 하는 것: 모든 '('가 그 뒤에서 짝이 되는 ')'와 순서대로 짝지어지는지 판별하는 함수


# 2. 아이디어
# - '('는 스택에 push하고, ')'를 만나면 스택에서 pop하여 짝을 맞춘다.
# - ')'가 나왔는데 스택이 비어 있으면 짝지을 '('가 없으므로 False
# - 문자열을 모두 순회한 뒤 스택이 비어 있어야 모든 괄호가 짝지어진 것
# - 자료구조: 스택 (list)


# 3. 풀이 계획
# 1) 첫 문자가 ')'이면 바로 False를 반환
# 2) 나머지 문자를 순회하며 '('는 push, ')'는 스택이 비어 있으면 False, 아니면 pop
# 3) 순회가 끝난 뒤 스택이 비어 있으면 True, 남아 있으면 False를 반환한다.


def solution(s):
    answer = True
    stack = []
    
    for idx  in range(0, len(s)):
        if s[idx] == '(':
            stack.append('(')
        else:
            if len(stack) == 0:
                return False
            else:
                stack.pop()

    if len(stack) != 0:
        answer = False

    return answer

