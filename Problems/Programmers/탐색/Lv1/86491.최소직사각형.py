# 프로그래머스 Lv1. 최소직사각형
# 분류: 완전탐색
# 핵심: 각 명함을 회전시켜 가로를 긴 변, 세로를 짧은 변으로 맞춘 뒤, 모든 명함의 최대 가로/최대 세로를 지갑 크기로 삼는다.
# 시간 복잡도: O(n)
"""
    1. 입력 크기를 정의: sizes의 길이를 n(명함 개수)이라 둔다.
    2. 코드에서 반복문·조건문의 실행 횟수를 입력 크기에 대한 함수로 센다.
    3. 상수 시간 연산(max, min, 비교, 대입)은 O(1)로 취급하고, 이런 연산이 반복문 안에서 몇 번 실행되는지 곱한다.
        -> 이 코드에서는 for w, h in sizes: 루프가 n번 실행되고, 
        -> 루프 내부(max, min 4번 정도)는 모두 O(1)이므로
        -> 전체 시간 = n × O(1) = O(n)
"""


# 공간 복잡도: O(1)
"""
    1. 입력 자체를 저장하는 공간은 보통 제외하고(입력은 이미 주어진 것이므로), 알고리즘이 추가로 사용하는 메모리만 센다.
    2. 입력 크기 n에 비례해서 커지는 자료구조(리스트, 딕셔너리 등)를 새로 만드는지 확인한다.
        -> 이 코드는 mw, mh, long, short, answer 같은 변수 몇 개만 사용하고, 
        -> n에 따라 크기가 늘어나는 자료구조를 만들지XX
        -> 추가 공간 = 변수 개수(고정) = O(1)
"""


# 1. 문제 이해
# - 입력: 명함들의 가로/세로 길이 2차원 배열 sizes (각 원소는 [w, h])
# - 출력: 모든 명함을 수납할 수 있는 가장 작은 지갑의 크기 (넓이)
# - 구해야 하는 것: 명함을 회전시켜도 되므로, 모든 명함을 담을 수 있는 최소 가로 x 세로 넓이


# 2. 아이디어
# - 명함은 회전 가능하므로 각 명함을 (긴 변, 짧은 변) 형태로 통일해서 비교한다.


# 3. 풀이 계획
# 1) 모든 명함을 순회하며 각 명함의 긴 변과 짧은 변을 구한다.
# 2) 지갑의 가로(mw)는 긴 변들의 최댓값, 세로(mh)는 짧은 변들의 최댓값으로 갱신한다.
# 3) 순회가 끝나면 mw * mh를 반환한다.


def solution(sizes):
    mw, mh = 1, 1
    for w, h in sizes:
        long = max(w, h)    
        short = min(w, h)

        # mw를 긴쪽으로
        mw = max(mw, long)
        mh = max(mh, short)

    answer = mw * mh
    return answer