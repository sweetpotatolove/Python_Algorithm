# 프로그래머스 Lv2. 게임 맵 최단거리
# 분류: 완전탐색(BFS)
# 핵심: (0,0)에서 BFS로 칸을 넓혀가며, 각 칸에 도달할 때 이전 칸까지의 거리 + 1을 기록해 도착 칸의 값을 최단 경로 길이로 삼는다.
# 시간 복잡도: O(n*m)
"""
    1. 입력 크기를 정의: 맵의 열 개수를 n, 행 개수를 m이라 두면 전체 칸 수는 n*m이다.
    2. 코드에서 반복문·조건문의 실행 횟수를 입력 크기에 대한 함수로 센다.
    3. 상수 시간 연산(비교, 대입, 인덱스 접근)은 O(1)로 취급하고, 이런 연산이 반복문 안에서 몇 번 실행되는지 곱한다.
        -> BFS(while queue)는 visited 체크 덕분에 각 칸을 정확히 한 번씩만 방문하므로 전체 방문 횟수는 n*m번이고,
        -> 방문할 때마다 for i in range(4): 4번씩 이웃을 확인하므로
        -> 전체 시간 = n*m × 4 × O(1) = O(n*m)
"""


# 공간 복잡도: O(n*m)
"""
    1. 입력 자체를 저장하는 공간은 보통 제외하고(입력은 이미 주어진 것이므로), 알고리즘이 추가로 사용하는 메모리만 센다.
    2. 입력 크기 n*m에 비례해서 커지는 자료구조(리스트, 딕셔너리 등)를 새로 만드는지 확인한다.
        -> 이 코드는 맵과 같은 크기의 visited 2차원 배열과, 최대 n*m개의 칸을 담을 수 있는 BFS용 queue를 사용하므로
        -> 추가 공간 = 칸 수에 비례 = O(n*m)
"""


# 1. 문제 이해
# - 입력: n x m 크기의 게임 맵 maps (0은 벽, 1은 길)
# - 출력: (1,1)에서 (n,m)까지 이동하며 지나야 하는 칸 개수의 최솟값, 도달할 수 없으면 -1
# - 구해야 하는 것: 상하좌우로만 이동 가능한 격자에서 시작점부터 도착점까지의 최단 경로 길이(지나는 칸 수)


# 2. 아이디어
# - 그리드에서의 최단 거리 문제이므로 BFS를 사용한다. BFS는 시작점에서 가까운 칸부터 순서대로 방문하므로, 어떤 칸을 처음 방문하는 순간이 곧 그 칸까지의 최단 거리다.
# - visited 배열에 방문 여부와 "시작점부터 지나온 칸의 개수"를 함께 기록해, 새로운 칸을 방문할 때 이전 칸의 값 + 1로 채운다.
# - BFS가 끝난 뒤 도착 칸의 값이 0이면 방문한 적이 없다는 뜻이므로 -1을 반환하고, 아니면 그 값이 곧 최단 경로의 칸 수다.


# 3. 풀이 계획
# 1) 4방향 이동 배열(dr, dc)과 방문/거리 기록용 visited 배열(모두 0)을 준비하고, 시작 칸 visited[0][0]을 1로 표시한 뒤 큐에 (0, 0)을 넣는다.
# 2) 큐가 빌 때까지 칸을 꺼내며 4방향 이웃을 확인한다.
# 3) 이웃 칸이 격자 범위 안이고 벽이 아니며(maps == 1) 아직 방문하지 않았다면, visited 값을 현재 칸의 visited 값 + 1로 기록하고 큐에 넣는다.
# 4) BFS가 끝나면 도착 칸 visited[m-1][n-1]이 0인지 확인해 0이면 -1을, 아니면 그 값을 answer로 삼아 반환한다.


from collections import deque
dr = [0, 0, 1, -1]
dc = [1, -1, 0, 0]

def solution(maps):
    queue = deque()
    queue.append((0, 0))    # n, m = c, r
    n = len(maps[0])
    m = len(maps)

    visited = [[0] * n for _ in range(m)]
    visited[0][0] = 1
    while queue:
        c, r = queue.popleft()
        for i in range(4):
            nc, nr = c + dc[i], r + dr[i]

            # 격자 안이고, 길 안막혀있으면
            if 0 <= nr < m and 0 <= nc < n and maps[nr][nc] == 1:
                if visited[nr][nc] == 0:
                    visited[nr][nc] = visited[r][c] + 1
                    queue.append((nc, nr))


    if visited[m-1][n-1] == 0:
        answer = -1
    else:
        answer = visited[m-1][n-1]

    return answer